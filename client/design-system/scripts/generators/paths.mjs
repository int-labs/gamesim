import { readFile } from "node:fs/promises";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

/** The design-system package root. */
export const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");

/** Resolves a module or package file the way the package itself would. */
export const resolveFromRoot = createRequire(path.join(ROOT, "package.json")).resolve;

/** The installed version of a dependency (works for packages that do not export package.json). */
export async function installedVersion(name) {
  const manifest = path.join(ROOT, "node_modules", name, "package.json");
  return JSON.parse(await readFile(manifest, "utf8")).version;
}

